/**
 * Transactional outbox — single-process learning lab.
 *
 * What is REAL here:      H2 transactions (real ACID commits and rollbacks).
 * What is SIMULATED here: the message broker (an in-memory append-only log,
 *                         standing in for a Kafka topic) and process crashes
 *                         (a `Crash` exception raised at a chosen point; a
 *                         "restart" is just constructing fresh objects over the
 *                         same database file, exactly like a process restart
 *                         over a durable disk).
 *
 * Cast of characters:
 *   OrderService   — the producer. Owns orders.mv.db (tables: orders, outbox).
 *   Broker         — the messaging system. Durable, but a SEPARATE system:
 *                    it cannot join the database's transaction.
 *   Relay          — the message relay. Polls the outbox table, publishes to
 *                    the broker, marks rows as published.
 *   InventoryService — the consumer. Owns inventory.mv.db (tables: inventory,
 *                    processed_messages). Reads the broker log and decrements
 *                    stock for each order-placed event.
 *
 * Run the guided experiments (from this directory, so ../lib resolves):
 *   java -cp ../lib/h2.jar OutboxLab.java dual-write-crash
 *   java -cp ../lib/h2.jar OutboxLab.java outbox-survives-crash
 *   java -cp ../lib/h2.jar OutboxLab.java relay-crash-duplicate
 *   java -cp ../lib/h2.jar OutboxLab.java idempotent-consumer
 *   java -cp ../lib/h2.jar OutboxLab.java all
 */
public class OutboxLab {

    /** Simulates the process dying at an exact point in the code. */
    static class Crash extends RuntimeException {
        Crash(String message) {
            super(message);
        }
    }

    // -----------------------------------------------------------------------
    // The broker: durable, ordered, append-only — but OUTSIDE the database.
    // -----------------------------------------------------------------------

    /** One message on the log: exactly the three fields the outbox row carries. */
    record Message(String messageId, String topic, String payload) {
    }

    /**
     * Stands in for one Kafka topic / RabbitMQ queue.
     *
     * It survives producer crashes (it is a separate system), and consumers
     * read it as an ordered log. What it can NOT do is take part in the
     * producer's database transaction — that impossibility is the entire
     * reason the outbox pattern exists.
     */
    static class Broker {
        final List<Message> log = new ArrayList<>();

        void publish(String messageId, String topic, String payload) {
            log.add(new Message(messageId, topic, payload));
        }
    }

    // -----------------------------------------------------------------------
    // Producer side: the order service and its database
    // -----------------------------------------------------------------------

    /** A row of the orders table, printed the way the Python lab printed it. */
    record Order(String id, String item, int qty) {
        @Override
        public String toString() {
            return "('" + id + "', '" + item + "', " + qty + ")";
        }
    }

    /** An unpublished outbox row, printed the way the Python lab printed it. */
    record OutboxRow(long seq, String messageId, String topic, String payload) {
        @Override
        public String toString() {
            return "(" + seq + ", '" + messageId + "', '" + topic + "', '" + payload + "')";
        }
    }

    static class OrderService implements AutoCloseable {
        final String dbPath;
        final Connection conn;

        OrderService(String dbPath) throws SQLException {
            this.dbPath = dbPath;
            this.conn = connect(dbPath);
            try (Statement st = conn.createStatement()) {
                st.execute(
                        "CREATE TABLE IF NOT EXISTS orders ("
                                + " id VARCHAR PRIMARY KEY, item VARCHAR, qty INT)");
                st.execute(
                        "CREATE TABLE IF NOT EXISTS outbox ("
                                + " seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY," // preserves send order
                                + " message_id VARCHAR UNIQUE,"
                                + " topic VARCHAR, payload VARCHAR,"
                                + " published_at TIMESTAMP)");                                // NULL = not yet sent
            }
            conn.commit();
        }

        // --- the WRONG way: dual write ------------------------------------

        String placeOrderDualWrite(Broker broker, String item, int qty) throws SQLException {
            return placeOrderDualWrite(broker, item, qty, false);
        }

        /**
         * Write to the DB, then publish to the broker: two separate systems,
         * two separate writes, no shared transaction.
         */
        String placeOrderDualWrite(Broker broker, String item, int qty, boolean crashBetween)
                throws SQLException {
            String orderId = shortId();
            try (PreparedStatement ps = conn.prepareStatement(
                    "INSERT INTO orders (id, item, qty) VALUES (?, ?, ?)")) {
                ps.setString(1, orderId);
                ps.setString(2, item);
                ps.setInt(3, qty);
                ps.executeUpdate();
            }
            conn.commit();                          // write #1: durable in the DB

            if (crashBetween) {
                throw new Crash("process died after DB commit, before publish");
            }

            broker.publish(                          // write #2: a different system
                    shortId(),
                    "order-placed",
                    json(orderId, item, qty));
            return orderId;
        }

        // --- the RIGHT way: outbox ----------------------------------------

        /**
         * ONE local transaction writes both the order and the outgoing
         * message. Either both become durable or neither does.
         */
        String placeOrderOutbox(String item, int qty) throws SQLException {
            String orderId = shortId();
            String messageId = shortId();
            try {                                   // one atomic H2 transaction
                try (PreparedStatement ps = conn.prepareStatement(
                        "INSERT INTO orders (id, item, qty) VALUES (?, ?, ?)")) {
                    ps.setString(1, orderId);
                    ps.setString(2, item);
                    ps.setInt(3, qty);
                    ps.executeUpdate();
                }
                try (PreparedStatement ps = conn.prepareStatement(
                        "INSERT INTO outbox (message_id, topic, payload)"
                                + " VALUES (?, ?, ?)")) {
                    ps.setString(1, messageId);
                    ps.setString(2, "order-placed");
                    ps.setString(3, json(orderId, item, qty));
                    ps.executeUpdate();
                }
                conn.commit();
            } catch (SQLException | RuntimeException e) {
                conn.rollback();                    // neither insert survives
                throw e;
            }
            return orderId;
        }

        List<Order> orders() throws SQLException {
            List<Order> rows = new ArrayList<>();
            try (Statement st = conn.createStatement();
                 ResultSet rs = st.executeQuery("SELECT id, item, qty FROM orders")) {
                while (rs.next()) {
                    rows.add(new Order(rs.getString(1), rs.getString(2), rs.getInt(3)));
                }
            }
            conn.commit();                          // end the read transaction
            return rows;
        }

        List<OutboxRow> unpublishedOutboxRows() throws SQLException {
            List<OutboxRow> rows = readUnpublished(conn);
            conn.commit();                          // end the read transaction
            return rows;
        }

        @Override
        public void close() throws SQLException {
            conn.close();
        }
    }

    // -----------------------------------------------------------------------
    // The relay: outbox table -> broker
    // -----------------------------------------------------------------------

    /**
     * Polls the producer's outbox table and publishes pending rows.
     *
     * Note the unavoidable gap: `publish` and `mark as published` are again
     * two systems, so the relay can crash between them. That is why delivery
     * is AT-LEAST-once, never exactly-once.
     */
    static class Relay implements AutoCloseable {
        final Connection conn;

        Relay(String dbPath) throws SQLException {
            this.conn = connect(dbPath);
        }

        int pollOnce(Broker broker) throws SQLException {
            return pollOnce(broker, false);
        }

        int pollOnce(Broker broker, boolean crashAfterPublish) throws SQLException {
            List<OutboxRow> rows = readUnpublished(conn);
            conn.commit();                          // end the read transaction
            int sent = 0;
            for (OutboxRow row : rows) {
                broker.publish(row.messageId(), row.topic(), row.payload());
                if (crashAfterPublish) {
                    throw new Crash(
                            "relay died after publishing message " + row.messageId()
                                    + ", before marking it published");
                }
                try (PreparedStatement ps = conn.prepareStatement(
                        "UPDATE outbox SET published_at = CURRENT_TIMESTAMP"
                                + " WHERE seq = ?")) {
                    ps.setLong(1, row.seq());
                    ps.executeUpdate();
                }
                conn.commit();
                sent += 1;
            }
            return sent;
        }

        @Override
        public void close() throws SQLException {
            conn.close();
        }
    }

    // -----------------------------------------------------------------------
    // Consumer side: the inventory service and its own database
    // -----------------------------------------------------------------------

    /** What one call to consumeAll did: messages applied, duplicates skipped. */
    record Consumed(int applied, int skipped) {
    }

    static class InventoryService implements AutoCloseable {
        final boolean idempotent;
        final Connection conn;

        InventoryService(String dbPath, boolean idempotent) throws SQLException {
            this.idempotent = idempotent;
            this.conn = connect(dbPath);
            try (Statement st = conn.createStatement()) {
                st.execute(
                        "CREATE TABLE IF NOT EXISTS inventory ("
                                + " item VARCHAR PRIMARY KEY, stock INT)");
                st.execute(
                        "CREATE TABLE IF NOT EXISTS processed_messages ("
                                + " message_id VARCHAR PRIMARY KEY)");   // the 'inbox' dedupe table
                st.execute(
                        "CREATE TABLE IF NOT EXISTS consumer_offset ("
                                + " id INT PRIMARY KEY CHECK (id = 1), next_index INT)");
                // H2 has no INSERT OR IGNORE: seed the offset row only when absent,
                // so a restarted consumer keeps the offset it already committed.
                try (ResultSet rs = st.executeQuery(
                        "SELECT count(*) FROM consumer_offset WHERE id = 1")) {
                    rs.next();
                    if (rs.getInt(1) == 0) {
                        st.executeUpdate(
                                "INSERT INTO consumer_offset (id, next_index)"
                                        + " VALUES (1, 0)");
                    }
                }
            }
            conn.commit();
        }

        Integer stock(String item) throws SQLException {
            Integer value = null;
            try (PreparedStatement ps = conn.prepareStatement(
                    "SELECT stock FROM inventory WHERE item = ?")) {
                ps.setString(1, item);
                try (ResultSet rs = ps.executeQuery()) {
                    if (rs.next()) {
                        value = rs.getInt(1);
                    }
                }
            }
            conn.commit();                          // end the read transaction
            return value;
        }

        void setStock(String item, int qty) throws SQLException {
            try (PreparedStatement ps = conn.prepareStatement(
                    "MERGE INTO inventory (item, stock) KEY (item) VALUES (?, ?)")) {
                ps.setString(1, item);
                ps.setInt(2, qty);
                ps.executeUpdate();
            }
            conn.commit();
        }

        Consumed consumeAll(Broker broker) throws SQLException {
            return consumeAll(broker, false);
        }

        /**
         * Read every not-yet-consumed message from the broker log and apply
         * it. With idempotent=true, a messageId seen before is skipped —
         * the skip-check and the stock update share one transaction.
         */
        Consumed consumeAll(Broker broker, boolean narrate) throws SQLException {
            int applied = 0, skipped = 0;
            while (true) {
                int nextIndex;
                try (Statement st = conn.createStatement();
                     ResultSet rs = st.executeQuery(
                             "SELECT next_index FROM consumer_offset WHERE id = 1")) {
                    rs.next();
                    nextIndex = rs.getInt(1);
                }
                conn.commit();                      // end the read transaction
                if (nextIndex >= broker.log.size()) {
                    return new Consumed(applied, skipped);
                }
                Message msg = broker.log.get(nextIndex);
                String item = jsonString(msg.payload(), "item");
                int qty = jsonInt(msg.payload(), "qty");
                boolean duplicate = false;
                try {                               // apply + dedupe-record + offset: one transaction
                    if (idempotent) {
                        try (PreparedStatement ps = conn.prepareStatement(
                                "SELECT 1 FROM processed_messages WHERE message_id = ?")) {
                            ps.setString(1, msg.messageId());
                            try (ResultSet rs = ps.executeQuery()) {
                                duplicate = rs.next();
                            }
                        }
                        if (!duplicate) {
                            try (PreparedStatement ps = conn.prepareStatement(
                                    "INSERT INTO processed_messages (message_id)"
                                            + " VALUES (?)")) {
                                ps.setString(1, msg.messageId());
                                ps.executeUpdate();
                            }
                        }
                    }
                    if (!duplicate) {
                        try (PreparedStatement ps = conn.prepareStatement(
                                "UPDATE inventory SET stock = stock - ?"
                                        + " WHERE item = ?")) {
                            ps.setInt(1, qty);
                            ps.setString(2, item);
                            ps.executeUpdate();
                        }
                    }
                    try (PreparedStatement ps = conn.prepareStatement(
                            "UPDATE consumer_offset SET next_index = ? WHERE id = 1")) {
                        ps.setInt(1, nextIndex + 1);
                        ps.executeUpdate();
                    }
                    conn.commit();
                } catch (SQLException | RuntimeException e) {
                    conn.rollback();                // effect AND dedupe record roll back together
                    throw e;
                }
                if (duplicate) {
                    skipped += 1;
                    if (narrate) {
                        System.out.println(
                                "    consumer: message " + msg.messageId()
                                        + " already processed — SKIPPED");
                    }
                } else {
                    applied += 1;
                    if (narrate) {
                        System.out.println(
                                "    consumer: applied message " + msg.messageId()
                                        + " (" + item + " x" + qty + ")"
                                        + " -> stock now " + stock(item));
                    }
                }
            }
        }

        @Override
        public void close() throws SQLException {
            conn.close();
        }
    }

    // -----------------------------------------------------------------------
    // Shared plumbing
    // -----------------------------------------------------------------------

    /**
     * A file-backed H2 database, with autocommit OFF so every commit and
     * rollback in this lab is one written by hand. The file survives a
     * simulated process restart exactly as a real database file does.
     */
    static Connection connect(String dbPath) throws SQLException {
        Connection conn = DriverManager.getConnection("jdbc:h2:" + dbPath, "sa", "");
        conn.setAutoCommit(false);
        return conn;
    }

    /** The relay's query, and the producer's view of it — one SQL statement, one place. */
    static List<OutboxRow> readUnpublished(Connection conn) throws SQLException {
        List<OutboxRow> rows = new ArrayList<>();
        try (Statement st = conn.createStatement();
             ResultSet rs = st.executeQuery(
                     "SELECT seq, message_id, topic, payload FROM outbox"
                             + " WHERE published_at IS NULL ORDER BY seq")) {
            while (rs.next()) {
                rows.add(new OutboxRow(rs.getLong(1), rs.getString(2), rs.getString(3), rs.getString(4)));
            }
        }
        return rows;
    }

    static String shortId() {
        return UUID.randomUUID().toString().substring(0, 8);
    }

    /** The event payload. Hand-rolled so that H2 stays this lab's only dependency. */
    static String json(String orderId, String item, int qty) {
        return "{\"order_id\": \"" + orderId + "\", \"item\": \"" + item + "\", \"qty\": " + qty + "}";
    }

    static String jsonString(String payload, String field) {
        int start = payload.indexOf("\"" + field + "\": \"") + field.length() + 5;
        return payload.substring(start, payload.indexOf('"', start));
    }

    static int jsonInt(String payload, String field) {
        int start = payload.indexOf("\"" + field + "\": ") + field.length() + 4;
        int end = start;
        while (end < payload.length() && Character.isDigit(payload.charAt(end))) end++;
        return Integer.parseInt(payload.substring(start, end));
    }

    static void closeAll(AutoCloseable... resources) {
        for (AutoCloseable resource : resources) {
            if (resource == null) continue;
            try {
                resource.close();
            } catch (Exception ignored) {
                // a lab teardown failure must never mask the experiment's output
            }
        }
    }

    // -----------------------------------------------------------------------
    // Guided experiments
    // -----------------------------------------------------------------------

    /**
     * Fresh database files for one experiment, so every run starts from zero.
     * H2 writes `<name>.mv.db` (and `<name>.trace.db` if anything goes wrong);
     * both are deleted here, the way the Python lab deleted its `.db` files.
     */
    static String[] freshPaths(String name) {
        String base = "./.lab-" + name;
        String[] paths = {base + "-orders", base + "-inventory"};
        for (String path : paths) {
            new File(path + ".mv.db").delete();
            new File(path + ".trace.db").delete();
        }
        return paths;
    }

    static void experimentDualWriteCrash() throws SQLException {
        System.out.println("=".repeat(72));
        System.out.println("EXPERIMENT 1: dual write, crash between DB commit and publish");
        System.out.println("=".repeat(72));
        String ordersDb = freshPaths("exp1")[0];
        Broker broker = new Broker();
        OrderService svc = new OrderService(ordersDb);
        System.out.println("Placing order for 2 x red-mug with a crash injected between the");
        System.out.println("database commit and the broker publish...");
        try {
            svc.placeOrderDualWrite(broker, "red-mug", 2, true);
        } catch (Crash e) {
            System.out.println("  CRASH: " + e.getMessage());
        }
        System.out.println("Process 'restarts' (new objects, same database file):");
        OrderService svc2 = new OrderService(ordersDb);
        System.out.println("  orders table:        " + svc2.orders());
        System.out.println("  broker log:          " + broker.log.size() + " messages");
        System.out.println();
        System.out.println("VERDICT: the order is durably saved but the event never existed.");
        System.out.println("Nothing in the system knows anything is missing — there is no");
        System.out.println("record of the intent to send. This is the silent-loss failure.");
        System.out.println();
        closeAll(svc, svc2);
    }

    static void experimentOutboxSurvivesCrash() throws SQLException {
        System.out.println("=".repeat(72));
        System.out.println("EXPERIMENT 2: outbox, crash at the same point — nothing is lost");
        System.out.println("=".repeat(72));
        String ordersDb = freshPaths("exp2")[0];
        Broker broker = new Broker();
        OrderService svc = new OrderService(ordersDb);
        svc.placeOrderOutbox("red-mug", 2);
        System.out.println("Order + outbox row committed in ONE transaction. The process now");
        System.out.println("crashes before any relay ever ran (same crash point as before).");
        System.out.println("Process restarts:");
        OrderService svc2 = new OrderService(ordersDb);
        System.out.println("  orders table:        " + svc2.orders());
        System.out.println("  unpublished outbox:  " + svc2.unpublishedOutboxRows());
        Relay relay = new Relay(ordersDb);
        int sent = relay.pollOnce(broker);
        System.out.println("Relay polls once: published " + sent + " message(s).");
        System.out.println("  broker log:          " + broker.log.size() + " messages");
        System.out.println();
        System.out.println("VERDICT: the intent to send was committed WITH the order, so a");
        System.out.println("crash only delays the message; it can never erase it.");
        System.out.println();
        closeAll(svc, svc2, relay);
    }

    static void experimentRelayCrashDuplicate() throws SQLException {
        experimentRelayCrashDuplicate(false, true);
    }

    static void experimentRelayCrashDuplicate(boolean idempotent, boolean banner) throws SQLException {
        if (banner) {
            System.out.println("=".repeat(72));
            System.out.println("EXPERIMENT 3: relay crashes after publish, before marking");
            System.out.println("=".repeat(72));
        }
        String[] paths = freshPaths("exp3" + (idempotent ? "i" : ""));
        String ordersDb = paths[0], invDb = paths[1];
        Broker broker = new Broker();
        OrderService svc = new OrderService(ordersDb);
        InventoryService inv = new InventoryService(invDb, idempotent);
        inv.setStock("red-mug", 10);
        svc.placeOrderOutbox("red-mug", 2);
        System.out.println("Stock starts at 10. One order for 2 x red-mug is in the outbox.");
        Relay relay = new Relay(ordersDb);
        try {
            relay.pollOnce(broker, true);
        } catch (Crash e) {
            System.out.println("  CRASH: " + e.getMessage());
        }
        System.out.println("Relay restarts and polls again. The row is still unmarked, so:");
        Relay relay2 = new Relay(ordersDb);
        relay2.pollOnce(broker);
        System.out.println("  broker log now holds " + broker.log.size()
                + " copies of the same message_id.");
        String label = idempotent ? "IDEMPOTENT" : "NAIVE";
        System.out.println("Consumer (" + label + ") processes the log:");
        inv.consumeAll(broker, true);
        System.out.println("  final stock: " + inv.stock("red-mug") + " (correct answer: 8)");
        System.out.println();
        if (idempotent) {
            System.out.println("VERDICT: the duplicate reached the consumer but was recognized");
            System.out.println("by its message_id and skipped. At-least-once delivery +");
            System.out.println("idempotent processing = effectively-once OUTCOME.");
        } else {
            System.out.println("VERDICT: at-least-once delivery is the price of never losing a");
            System.out.println("message. A naive consumer turns the duplicate into wrong data.");
        }
        System.out.println();
        closeAll(svc, inv, relay, relay2);
    }

    static void experimentIdempotentConsumer() throws SQLException {
        System.out.println("=".repeat(72));
        System.out.println("EXPERIMENT 4: same relay crash, idempotent consumer");
        System.out.println("=".repeat(72));
        experimentRelayCrashDuplicate(true, false);
    }

    /** Thrown-through wrapper so the experiment map can hold plain lambdas. */
    interface Experiment {
        void run() throws SQLException;
    }

    static final Map<String, Experiment> EXPERIMENTS = new LinkedHashMap<>();

    static {
        EXPERIMENTS.put("dual-write-crash", OutboxLab::experimentDualWriteCrash);
        EXPERIMENTS.put("outbox-survives-crash", OutboxLab::experimentOutboxSurvivesCrash);
        EXPERIMENTS.put("relay-crash-duplicate", OutboxLab::experimentRelayCrashDuplicate);
        EXPERIMENTS.put("idempotent-consumer", OutboxLab::experimentIdempotentConsumer);
    }

    /**
     * Delete every database file this lab created. Called before each experiment
     * (so a previous crashed run cannot leak state into this one) AND from a
     * shutdown hook (so a finished run leaves the directory as it found it).
     * Only the "before" half is load-bearing for correctness; the "after" half
     * is housekeeping.
     */
    static void deleteLabDatabases() {
        File dir = new File(".");
        File[] files = dir.listFiles((d, name) ->
                name.startsWith(".lab-") && (name.endsWith(".mv.db") || name.endsWith(".trace.db")));
        if (files != null) {
            for (File f : files) f.delete();
        }
    }

    public static void main(String[] args) throws Exception {
        Runtime.getRuntime().addShutdownHook(new Thread(OutboxLab::deleteLabDatabases));
        String choice = args.length > 0 ? args[0] : "all";
        if (choice.equals("all")) {
            for (Experiment experiment : EXPERIMENTS.values()) {
                experiment.run();
            }
        } else if (EXPERIMENTS.containsKey(choice)) {
            EXPERIMENTS.get(choice).run();
        } else {
            System.out.println("usage: java -cp ../lib/h2.jar OutboxLab.java ["
                    + String.join("|", EXPERIMENTS.keySet()) + "|all]");
            System.exit(1);
        }
    }
}
