    /** Build an ordered map from alternating key/value arguments. */
    static Map<String, Object> map(Object... keyValues) {
        Map<String, Object> m = new LinkedHashMap<>();
        for (int i = 0; i < keyValues.length; i += 2) m.put((String) keyValues[i], keyValues[i + 1]);
        return m;
    }

    /** A JDBC failure the lab has no interesting answer for. */
    static class DbError extends RuntimeException {
        DbError(Throwable cause) { super(cause); }
    }

    /**
     * A thin wrapper over one H2 connection, so the lab code above reads like
     * the lesson instead of like plumbing. Auto-commit is OFF everywhere:
     * transactions are explicit, which is the whole point of §9 step 2.
     */
    static class Db {

        /** Every store this process opened, so we can close and delete them. */
        private static final Map<String, Connection> OPEN = new LinkedHashMap<>();

        static {
            Runtime.getRuntime().addShutdownHook(new Thread(Db::wipeAll));
        }

        final Connection conn;

        private Db(Connection conn) { this.conn = conn; }

        /**
         * Open {@code <name>.mv.db} in this directory, deleting any leftovers
         * first — a store always starts empty, so scenarios are re-runnable.
         */
        static Db freshStore(String name) {
            closeAndDelete(name);
            try {
                Connection conn = DriverManager.getConnection("jdbc:h2:./" + name, "sa", "");
                conn.setAutoCommit(false);
                OPEN.put(name, conn);
                return new Db(conn);
            } catch (SQLException e) {
                throw new DbError(e);
            }
        }

        private static void closeAndDelete(String name) {
            Connection previous = OPEN.remove(name);
            if (previous != null) {
                try { previous.close(); } catch (SQLException ignored) { }
            }
            new File(name + ".mv.db").delete();
            new File(name + ".trace.db").delete();
        }

        /** Leave no stray H2 files behind when the JVM exits. */
        static void wipeAll() {
            for (String name : List.copyOf(OPEN.keySet())) closeAndDelete(name);
        }

        /** Python's `with db:` — commit on success, roll back on any exception. */
        void transaction(Runnable body) {
            try {
                body.run();
                commit();
            } catch (RuntimeException e) {
                rollback();
                throw e;
            }
        }

        void commit() {
            try { conn.commit(); } catch (SQLException e) { throw new DbError(e); }
        }

        void rollback() {
            try { conn.rollback(); } catch (SQLException e) { throw new DbError(e); }
        }

        void ddl(String sql) {
            try (Statement s = conn.createStatement()) { s.execute(sql); }
            catch (SQLException e) { throw new DbError(e); }
        }

        /** Run a statement; return how many rows it changed. */
        int update(String sql, Object... args) {
            try (PreparedStatement ps = prepare(sql, args)) { return ps.executeUpdate(); }
            catch (SQLException e) { throw new DbError(e); }
        }

        /** The first row, or null when the query matched nothing. */
        Object[] queryRow(String sql, Object... args) {
            List<Object[]> rows = queryRows(sql, args);
            return rows.isEmpty() ? null : rows.get(0);
        }

        List<Object[]> queryRows(String sql, Object... args) {
            try (PreparedStatement ps = prepare(sql, args); ResultSet rs = ps.executeQuery()) {
                int columns = rs.getMetaData().getColumnCount();
                List<Object[]> rows = new ArrayList<>();
                while (rs.next()) {
                    Object[] row = new Object[columns];
                    for (int i = 0; i < columns; i++) row[i] = rs.getObject(i + 1);
                    rows.add(row);
                }
                return rows;
            } catch (SQLException e) {
                throw new DbError(e);
            }
        }

        int queryInt(String sql, Object... args) {
            return ((Number) queryRow(sql, args)[0]).intValue();
        }

        double queryDouble(String sql, Object... args) {
            Object value = queryRow(sql, args)[0];
            return value == null ? 0.0 : ((Number) value).doubleValue();
        }

        private PreparedStatement prepare(String sql, Object... args) throws SQLException {
            PreparedStatement ps = conn.prepareStatement(sql);
            for (int i = 0; i < args.length; i++) ps.setObject(i + 1, args[i]);
            return ps;
        }
    }

    /**
     * The smallest JSON that can hold an event payload. The JDK ships no JSON
     * parser and H2 is this lab's only dependency; the encoding is incidental,
     * the event feed is the lesson.
     */
    static final class Json {

        static String write(Object value) {
            StringBuilder out = new StringBuilder();
            writeTo(out, value);
            return out.toString();
        }

        @SuppressWarnings("unchecked")
        private static void writeTo(StringBuilder out, Object value) {
            switch (value) {
                case null -> out.append("null");
                case String s -> out.append('"').append(s.replace("\\", "\\\\").replace("\"", "\\\"")).append('"');
                case Number n -> out.append(n instanceof Integer || n instanceof Long
                        ? n.toString() : Double.toString(n.doubleValue()));
                case Map<?, ?> m -> {
                    out.append('{');
                    boolean first = true;
                    for (Map.Entry<String, Object> e : ((Map<String, Object>) m).entrySet()) {
                        if (!first) out.append(',');
                        first = false;
                        writeTo(out, e.getKey());
                        out.append(':');
                        writeTo(out, e.getValue());
                    }
                    out.append('}');
                }
                case List<?> l -> {
                    out.append('[');
                    for (int i = 0; i < l.size(); i++) {
                        if (i > 0) out.append(',');
                        writeTo(out, l.get(i));
                    }
                    out.append(']');
                }
                default -> throw new IllegalArgumentException("cannot encode " + value.getClass());
            }
        }

        @SuppressWarnings("unchecked")
        static Map<String, Object> readObject(String text) {
            return (Map<String, Object>) new Parser(text).value();
        }

        private static final class Parser {
            private final String text;
            private int at;

            Parser(String text) { this.text = text; }

            Object value() {
                skipSpace();
                char c = text.charAt(at);
                if (c == '{') return object();
                if (c == '[') return array();
                if (c == '"') return string();
                if (text.startsWith("null", at)) { at += 4; return null; }
                return number();
            }

            private Map<String, Object> object() {
                Map<String, Object> m = new LinkedHashMap<>();
                at++;                               // '{'
                skipSpace();
                if (text.charAt(at) == '}') { at++; return m; }
                while (true) {
                    skipSpace();
                    String key = string();
                    skipSpace();
                    at++;                           // ':'
                    m.put(key, value());
                    skipSpace();
                    if (text.charAt(at++) == '}') return m;   // else it was ','
                }
            }

            private List<Object> array() {
                List<Object> list = new ArrayList<>();
                at++;                               // '['
                skipSpace();
                if (text.charAt(at) == ']') { at++; return list; }
                while (true) {
                    list.add(value());
                    skipSpace();
                    if (text.charAt(at++) == ']') return list;   // else it was ','
                }
            }

            private String string() {
                StringBuilder sb = new StringBuilder();
                at++;                               // opening quote
                while (text.charAt(at) != '"') {
                    char c = text.charAt(at++);
                    sb.append(c == '\\' ? text.charAt(at++) : c);
                }
                at++;                               // closing quote
                return sb.toString();
            }

            private Double number() {
                int start = at;
                while (at < text.length() && "+-.eE0123456789".indexOf(text.charAt(at)) >= 0) at++;
                return Double.valueOf(text.substring(start, at));
            }

            private void skipSpace() {
                while (at < text.length() && Character.isWhitespace(text.charAt(at))) at++;
            }
        }
    }
